import { adminLeadsRouter, advertisingRouter, contactRouter, dataLicenceRouter, demoRequestsRouter } from "./modules/leads/leads.routes.js";
import { adminNewsRouter, newsRouter } from "./modules/news/news.routes.js";
import { adminNewsletterRouter, newsletterRouter } from "./modules/newsletter/newsletter.routes.js";
import { adminPricingRouter, pricingRouter } from "./modules/pricing/pricing.routes.js";
import { adminAirportsRouter, airportsRouter } from "./modules/airports/airports.routes.js";
import { adminAuthRouter } from "./modules/admin-auth/admin-auth.routes.js";
import { authRouter } from "./modules/auth/auth.routes.js";
import { adminCategoriesRouter, categoriesRouter } from "./modules/categories/category.routes.js";
import { adminBillingRouter, billingRouter } from "./modules/billing/billing.routes.js";
import { adminEnquiriesRouter, enquiriesRouter, myEnquiriesRouter, providerEnquiriesRouter } from "./modules/enquiries/enquiry.routes.js";
import { favoritesRouter } from "./modules/favorites/favorites.routes.js";
